#!/usr/bin/env bash
set -euo pipefail

if [[ $# -lt 1 ]]; then
  echo "usage: $0 <baseline_current|more_conservative|profit_tighter|trend_defensive|ultra_selective|fast_reprice_guarded|one_level_defensive|spread_quality_guarded>" >&2
  exit 2
fi

PROFILE="$1"
ROOT="${LIGHTER_MM_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
LOG_ROOT="${CHALLENGER_LOG_ROOT:-$ROOT/logs/challengers}"
LOG_DIR="${LOG_DIR:-$LOG_ROOT/$PROFILE}"
