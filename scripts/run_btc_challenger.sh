    ;;
  profit_tighter)
    export CJ_SPREAD_MULTIPLIER="${CJ_SPREAD_MULTIPLIER:-2.1}"
    export CJ_MIN_HALF_SPREAD_BPS="${CJ_MIN_HALF_SPREAD_BPS:-6.0}"
    export DEFAULT_QUOTE_UPDATE_THRESHOLD_BPS="${DEFAULT_QUOTE_UPDATE_THRESHOLD_BPS:-30.0}"
    export TOXIC_FLOW_SPREAD_CAPTURE_FLOOR_BPS="${TOXIC_FLOW_SPREAD_CAPTURE_FLOOR_BPS:-0.55}"
    export TOXIC_FLOW_ADVERSE_THRESHOLD_BPS="${TOXIC_FLOW_ADVERSE_THRESHOLD_BPS:-2.4}"
    export ADVERSE_TREND_THRESHOLD_BPS="${ADVERSE_TREND_THRESHOLD_BPS:-14.0}"
    export ADVERSE_TREND_SIDE_ADVERSE_BPS="${ADVERSE_TREND_SIDE_ADVERSE_BPS:-2.1}"
    export ADVERSE_TREND_MARKOUT_LOSS_BPS="${ADVERSE_TREND_MARKOUT_LOSS_BPS:-1.4}"
    export INVENTORY_EXIT_HYSTERESIS_ENTER_RATIO="${INVENTORY_EXIT_HYSTERESIS_ENTER_RATIO:-1.05}"
    ;;
  trend_defensive)
    export CJ_SPREAD_MULTIPLIER="${CJ_SPREAD_MULTIPLIER:-2.6}"
    export TOXIC_FLOW_SPREAD_CAPTURE_FLOOR_BPS="${TOXIC_FLOW_SPREAD_CAPTURE_FLOOR_BPS:-0.9}"
    export TOXIC_FLOW_ADVERSE_THRESHOLD_BPS="${TOXIC_FLOW_ADVERSE_THRESHOLD_BPS:-1.8}"
    export ADVERSE_TREND_THRESHOLD_BPS="${ADVERSE_TREND_THRESHOLD_BPS:-8.0}"
    export ADVERSE_TREND_SIDE_ADVERSE_BPS="${ADVERSE_TREND_SIDE_ADVERSE_BPS:-1.1}"
    export ADVERSE_TREND_MARKOUT_LOSS_BPS="${ADVERSE_TREND_MARKOUT_LOSS_BPS:-0.6}"
    export ADVERSE_TREND_SPREAD_FLOOR_BPS="${ADVERSE_TREND_SPREAD_FLOOR_BPS:-0.8}"
    export ADVERSE_TREND_COOLDOWN_SECONDS="${ADVERSE_TREND_COOLDOWN_SECONDS:-300}"
    export INVENTORY_EXIT_HYSTERESIS_ENTER_RATIO="${INVENTORY_EXIT_HYSTERESIS_ENTER_RATIO:-0.9}"
    export INVENTORY_DERISK_START_RATIO="${INVENTORY_DERISK_START_RATIO:-0.65}"
    ;;
  ultra_selective)
    # Tests whether fewer, wider quotes improve markout quality enough to
    # compensate for reduced fill count.  It is intentionally paper-only until
    # it proves positive spread capture and non-negative 30s markouts.
    export CAPITAL_USAGE_PERCENT="${CAPITAL_USAGE_PERCENT:-0.08}"
    export DEFAULT_QUOTE_UPDATE_THRESHOLD_BPS="${DEFAULT_QUOTE_UPDATE_THRESHOLD_BPS:-45.0}"
    export MIN_ORDER_LIFETIME_SECONDS="${MIN_ORDER_LIFETIME_SECONDS:-8.0}"
    export MIN_REPRICE_IMPROVEMENT_BPS="${MIN_REPRICE_IMPROVEMENT_BPS:-5.0}"
    export CJ_SPREAD_MULTIPLIER="${CJ_SPREAD_MULTIPLIER:-3.4}"
    export CJ_MIN_HALF_SPREAD_BPS="${CJ_MIN_HALF_SPREAD_BPS:-13.0}"
    export TOXIC_FLOW_MIN_SAMPLES="${TOXIC_FLOW_MIN_SAMPLES:-8}"
    export TOXIC_FLOW_SPREAD_CAPTURE_FLOOR_BPS="${TOXIC_FLOW_SPREAD_CAPTURE_FLOOR_BPS:-1.25}"
    export TOXIC_FLOW_ADVERSE_THRESHOLD_BPS="${TOXIC_FLOW_ADVERSE_THRESHOLD_BPS:-1.35}"
    export TOXIC_FLOW_SEVERE_ADVERSE_BPS="${TOXIC_FLOW_SEVERE_ADVERSE_BPS:-4.5}"
    export TOXIC_FLOW_INVENTORY_RATIO_TRIGGER="${TOXIC_FLOW_INVENTORY_RATIO_TRIGGER:-0.15}"
    export TOXIC_FLOW_SPREAD_WIDEN_PER_ADVERSE_BPS="${TOXIC_FLOW_SPREAD_WIDEN_PER_ADVERSE_BPS:-0.14}"
    export TOXIC_FLOW_MAX_SPREAD_MULTIPLIER="${TOXIC_FLOW_MAX_SPREAD_MULTIPLIER:-2.8}"
    export ADVERSE_TREND_MIN_SIDE_SAMPLES="${ADVERSE_TREND_MIN_SIDE_SAMPLES:-3}"
    export ADVERSE_TREND_THRESHOLD_BPS="${ADVERSE_TREND_THRESHOLD_BPS:-6.0}"
    export ADVERSE_TREND_SIDE_ADVERSE_BPS="${ADVERSE_TREND_SIDE_ADVERSE_BPS:-0.9}"
    export ADVERSE_TREND_MARKOUT_LOSS_BPS="${ADVERSE_TREND_MARKOUT_LOSS_BPS:-0.35}"
