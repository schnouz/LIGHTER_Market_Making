    export ADVERSE_TREND_COOLDOWN_SECONDS="${ADVERSE_TREND_COOLDOWN_SECONDS:-420}"
    export INVENTORY_EXIT_TIGHTEN_PER_RATIO="${INVENTORY_EXIT_TIGHTEN_PER_RATIO:-0.65}"
    export INVENTORY_ADD_WIDEN_PER_RATIO="${INVENTORY_ADD_WIDEN_PER_RATIO:-1.05}"
    export INVENTORY_MAX_EXIT_TIGHTEN="${INVENTORY_MAX_EXIT_TIGHTEN:-0.55}"
    export INVENTORY_MAX_ADD_WIDEN="${INVENTORY_MAX_ADD_WIDEN:-0.95}"
    export INVENTORY_ADVERSE_BOOST_PER_BPS="${INVENTORY_ADVERSE_BOOST_PER_BPS:-0.06}"
    export INVENTORY_EXIT_HYSTERESIS_ENTER_RATIO="${INVENTORY_EXIT_HYSTERESIS_ENTER_RATIO:-0.60}"
    export INVENTORY_EXIT_HYSTERESIS_EXIT_RATIO="${INVENTORY_EXIT_HYSTERESIS_EXIT_RATIO:-0.25}"
    export INVENTORY_DERISK_START_RATIO="${INVENTORY_DERISK_START_RATIO:-0.45}"
