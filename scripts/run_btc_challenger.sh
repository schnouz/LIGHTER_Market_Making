export RESEARCH_LOG_MAX_TOTAL_MB="${RESEARCH_LOG_MAX_TOTAL_MB:-1024}"
export RESEARCH_LOG_CLEANUP_INTERVAL_SECONDS="${RESEARCH_LOG_CLEANUP_INTERVAL_SECONDS:-3600}"
export PYTHONUNBUFFERED=1

# Keep paper challengers gentle on the live VPS. They still use the same public
# Lighter feeds and dry-run fill simulator, but are not latency-critical.
export MIN_LOOP_INTERVAL="${MIN_LOOP_INTERVAL:-0.2}"
export SANITY_CHECK_INTERVAL="${SANITY_CHECK_INTERVAL:-30}"

case "$PROFILE" in
  baseline_current)
    # Mirrors the current live config as closely as possible.
    ;;
  more_conservative)
    export CAPITAL_USAGE_PERCENT="${CAPITAL_USAGE_PERCENT:-0.12}"
    export CJ_SPREAD_MULTIPLIER="${CJ_SPREAD_MULTIPLIER:-2.9}"
    export CJ_MIN_HALF_SPREAD_BPS="${CJ_MIN_HALF_SPREAD_BPS:-10.0}"
    export TOXIC_FLOW_SPREAD_CAPTURE_FLOOR_BPS="${TOXIC_FLOW_SPREAD_CAPTURE_FLOOR_BPS:-1.0}"
    export TOXIC_FLOW_ADVERSE_THRESHOLD_BPS="${TOXIC_FLOW_ADVERSE_THRESHOLD_BPS:-1.7}"
    export ADVERSE_TREND_THRESHOLD_BPS="${ADVERSE_TREND_THRESHOLD_BPS:-9.0}"
    export ADVERSE_TREND_SIDE_ADVERSE_BPS="${ADVERSE_TREND_SIDE_ADVERSE_BPS:-1.25}"
    export ADVERSE_TREND_MARKOUT_LOSS_BPS="${ADVERSE_TREND_MARKOUT_LOSS_BPS:-0.75}"
    export ADVERSE_TREND_COOLDOWN_SECONDS="${ADVERSE_TREND_COOLDOWN_SECONDS:-240}"
